// Deterministic Korean dialogue checks, independent of village physics/camera.
import assert from 'node:assert/strict'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser=await chromium.launch({channel:'chrome',headless:true})
try {
  const page=await browser.newPage({ignoreHTTPSErrors:true})
  const errors=[];page.on('pageerror',error=>errors.push(String(error)))
  await page.goto(process.env.REVIEW_URL || 'https://localhost:5173')
  await page.clock.install({time:new Date('2026-10-08T00:00:00Z')})
  await page.clock.pauseAt(new Date('2026-10-08T00:00:01Z'))
  await page.evaluate(async()=>{
    await import('/src/parange-planet.ts') // Load the actual UI fonts and styles.
    const {residentLines,createDialogueDeck}=await import('/src/resident-lines.ts')
    const {createPlanetDialogue}=await import('/src/planet-dialogue.ts')
    if(residentLines.length!==100||new Set(residentLines).size!==100||residentLines.some(line=>!/[가-힣]/.test(line)||/[a-z]/i.test(line)))throw Error('Expected 100 unique Korean lines')
    const deck=createDialogueDeck(),first=Array.from({length:100},deck),second=Array.from({length:100},deck)
    if(new Set(first).size!==100||new Set(second).size!==100||first[99]===second[0])throw Error('Dialogue shuffle repeats')
    const root=document.createElement('section');root.className='planet-screen planet-sky-game is-open';document.body.append(root)
    window.dialogue=createPlanetDialogue(root,()=>window.dialogue.setResident(null))
    window.dialogue.setResident({id:'korean-test',name:'별빛 모찌'})
    window.koreanLines=residentLines
  })
  const bubble=page.locator('.planet-dialogue'),next=page.locator('.planet-dialogue-next')
  assert.equal(await bubble.getAttribute('lang'),'en')
  assert.equal(await page.locator('.planet-dialogue-text').getAttribute('lang'),'ko')
  assert.equal(await page.locator('.planet-dialogue-channel').innerText(),'NEIGHBOR CHAT!')
  assert.equal(await page.locator('.planet-dialogue-exit').innerText(),'GLOBE VIEW ↗')
  assert.match(await page.locator('.planet-dialogue footer').innerText(),/DRAG TO LOOK AROUND/)
  assert.match(await next.innerText(),/READ IT ALL/)
  assert.equal(await bubble.evaluate(el=>getComputedStyle(el.querySelector('.planet-dialogue-text')).fontFamily.startsWith('"Planet Jua"')&&
    [...el.querySelectorAll('button,.planet-dialogue-name,.planet-dialogue-channel')].every(node=>getComputedStyle(node).fontFamily.startsWith('"Planet Lilita"'))),true)
  assert.equal(await page.locator('.planet-dialogue-text').innerText().then(text=>Array.from(text).length),1)
  await page.clock.runFor(200)
  assert.ok((await page.locator('.planet-dialogue-text').innerText()).length>1)
  await next.evaluate(el=>el.click())
  const full=await page.locator('.planet-dialogue-text').innerText()
  assert.equal(await page.evaluate(text=>window.koreanLines.includes(text),full),true)
  assert.equal(await page.locator('.planet-dialogue-announcement').textContent(),`별빛 모찌: ${full}`)
  assert.match(await next.innerText(),/TELL ME MORE/)
  await next.evaluate(el=>{el.click();el.click()})
  assert.notEqual(await page.locator('.planet-dialogue-text').innerText(),full)
  await page.emulateMedia({reducedMotion:'reduce'})
  await next.evaluate(el=>el.click())
  assert.equal(await bubble.evaluate(el=>el.classList.contains('is-typing')),false)
  const previous=await page.locator('.planet-dialogue-text').innerText()
  await page.clock.fastForward(8100)
  assert.notEqual(await page.locator('.planet-dialogue-text').innerText(),previous)
  await page.locator('.planet-dialogue-exit').evaluate(el=>el.click())
  await page.clock.fastForward(16000)
  assert.equal(await bubble.isVisible(),false)
  assert.equal(await page.locator('.planet-dialogue-announcement').textContent(),'')
  await page.evaluate(()=>window.dialogue.dispose())
  assert.equal(await bubble.count(),0)
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({koreanLines:100,uniqueDecks:true,typewriter:true,readAll:true,nextLine:true,announcement:true,reducedMotion:true,autoAdvance:true,cleanup:true,errors},null,2))
}finally{await browser.close()}
