import assert from 'node:assert/strict'
import {mkdtemp} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const output=await mkdtemp(join(tmpdir(),'parange-monitor-'))
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']})
try{
 const page=await browser.newPage({ignoreHTTPSErrors:true,permissions:['camera'],viewport:{width:1440,height:1100},reducedMotion:'reduce'}),errors=[]
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
 await page.goto((process.env.REVIEW_URL||'https://localhost:5173')+'/#archive')
 assert.equal(await page.locator('.ar-pagination').isVisible(),true)
 await page.getByRole('button',{name:'Next drawer'}).click()
 await page.waitForFunction(()=>document.querySelectorAll('.ar-index-item').length===4 && document.querySelector('.ar-product-canvas').dataset.cards==='4')
 await page.getByRole('button',{name:'Previous drawer'}).click()
 await page.waitForFunction(()=>document.querySelectorAll('.ar-index-item').length===25 && document.querySelector('.ar-product-canvas').dataset.cards==='25')
 await page.getByRole('button',{name:'Come out — summon robot'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.arrival==='arrived')
 await page.getByRole('button',{name:'Open archive case'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='open')
 assert.equal(await page.locator('.ar-product-canvas').getAttribute('data-focus'),'cassette-closeup')
 assert.equal(await page.locator('.ar-cabinet-wrap').getAttribute('data-camera-state'),'off')
 assert.equal(await page.locator('.ar-page').isVisible(),false)
 await page.screenshot({path:join(output,'tapes-focus.png')})
 await page.getByRole('button',{name:'Next drawer'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.cards==='4')
 await page.getByRole('button',{name:'Previous drawer'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.cards==='25')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.getByRole('button',{name:'Focus webcam monitor and start camera'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.cameraState==='live'&&document.querySelector('.ar-product-canvas').dataset.viewTransition==='idle')
 assert.equal(await page.locator('.ar-product-canvas').getAttribute('data-focus'),'monitor-closeup')
 assert.equal(await page.locator('.ar-grid').evaluate(el=>el.inert),true)
 assert.equal(await page.getByRole('button',{name:'Next drawer'}).isVisible(),false)
 await page.screenshot({path:join(output,'webcam-focus.png')})
 await page.keyboard.press('Escape')
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.viewTransition==='idle')
 assert.equal(await page.locator('.ar-product-canvas').getAttribute('data-focus'),'cassette-closeup')
 assert.equal(await page.locator('.ar-grid').evaluate(el=>el.inert),false)
 assert.equal(await page.locator('.ar-cabinet-wrap').getAttribute('data-camera-state'),'off')
 await page.setViewportSize({width:390,height:844});await page.waitForTimeout(150)
 await page.screenshot({path:join(output,'tapes-mobile.png')})
 for(const name of ['Previous drawer','Next drawer']){const b=await page.getByRole('button',{name}).boundingBox();assert.ok(b.x>=0&&b.x+b.width<=390&&b.y>100&&b.y<740)}
 await page.getByRole('button',{name:'Focus webcam monitor and start camera'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.cameraState==='live'&&document.querySelector('.ar-product-canvas').dataset.viewTransition==='idle')
 await page.screenshot({path:join(output,'webcam-mobile.png')})
 await page.getByRole('button',{name:'Close archive case'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='closed')
 assert.equal(await page.locator('.ar-cabinet-wrap').getAttribute('data-camera-state'),'off')
 assert.equal(await page.locator('.ar-pagination').isVisible(),true)
 // A denied camera still allows monitor focus and a return to the tapes.
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.evaluate(()=>{navigator.mediaDevices.getUserMedia=async()=>{throw new DOMException('Denied','NotAllowedError')}})
 await page.getByRole('button',{name:'Open archive case'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='open')
 await page.getByRole('button',{name:'Focus webcam monitor and start camera'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.cameraState==='error'&&document.querySelector('.ar-product-canvas').dataset.viewTransition==='idle')
 assert.equal(await page.locator('.ar-monitor-status').isVisible(),true)
 // A late grant after returning to tapes must release the new tracks.
 await page.evaluate(()=>{navigator.mediaDevices.getUserMedia=()=>new Promise(resolve=>{window.resolveTestCamera=()=>{const c=document.createElement('canvas');c.width=c.height=32;window.testCameraStream=c.captureStream(1);resolve(window.testCameraStream)}})})
 await page.getByRole('button',{name:'Retry camera'}).click()
 await page.getByRole('button',{name:'Connecting to camera'}).waitFor()
 await page.keyboard.press('Escape')
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.focus==='cassette-closeup'&&document.querySelector('.ar-product-canvas').dataset.viewTransition==='idle')
 await page.evaluate(()=>window.resolveTestCamera())
 await page.waitForFunction(()=>window.testCameraStream.getTracks().every(t=>t.readyState==='ended'))
 await page.keyboard.press('Escape')
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='closed')
 assert.deepEqual(errors,[])
 console.log(`PASS: cassette-first close-up, monitor click starts camera and transitions, tape return, lateral triangle pagination, mobile, closing from webcam, denied/late camera permission. Screenshots: ${output}`)
}finally{await browser.close()}
