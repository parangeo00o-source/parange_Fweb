import assert from 'node:assert/strict'
import {mkdtemp} from 'node:fs/promises'
import {tmpdir} from 'node:os'
import {join} from 'node:path'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const output=await mkdtemp(join(tmpdir(),'parange-opening-'))
const browser=await chromium.launch({channel:'chrome',headless:true})
try{
 const page=await browser.newPage({ignoreHTTPSErrors:true,viewport:{width:1440,height:1100},reducedMotion:'reduce'}),errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto((process.env.REVIEW_URL||'https://localhost:5173')+'/#archive')
 await page.getByRole('button',{name:'Come out — summon robot'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.arrival==='arrived')
 const canvas=page.locator('.ar-product-canvas')
 assert.ok(Math.abs(Number(await canvas.getAttribute('data-azimuth'))+Math.PI/2)<.01,'Seated dog faces the viewer')
 const background=await page.locator('.ar-atmosphere').evaluate(e=>getComputedStyle(e).backgroundImage)
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.getByRole('button',{name:'Open archive case'}).click()
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.casePhase==='placing')
 assert.equal(await canvas.getAttribute('data-lid-angle'),'0')
 assert.equal(await canvas.getAttribute('data-zoom-progress'),'0.000')
 await page.screenshot({path:join(output,'placing.png')})
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.casePhase==='settling')
 assert.equal(await canvas.getAttribute('data-lid-angle'),'0')
 await page.waitForFunction(()=>document.querySelector('.ar-product-canvas').dataset.casePhase==='open-hold')
 const overview=Number(await canvas.getAttribute('data-camera-distance'))
 assert.equal(await canvas.getAttribute('data-lid-angle'),'106')
 assert.equal(await canvas.getAttribute('data-zoom-progress'),'0.000')
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='open')
 const closeup=Number(await canvas.getAttribute('data-camera-distance'))
 assert.ok(closeup<overview*.65,`${closeup} must bring the tapes closer than ${overview}`)
 assert.equal(await canvas.getAttribute('data-focus'),'cassette-closeup')
 assert.equal(await page.locator('.ar-viewer-pagination').isVisible(),true)
 assert.ok(Math.abs(Number(await canvas.getAttribute('data-azimuth')))<.01)
 assert.equal(await page.locator('.ar-atmosphere').evaluate(e=>getComputedStyle(e).backgroundImage),background)
 assert.equal(await page.locator('.ar-cabinet-wrap').evaluate(e=>getComputedStyle(e).backgroundColor),'rgba(0, 0, 0, 0)')
 await page.screenshot({path:join(output,'closeup-desktop.png')})
 await page.setViewportSize({width:390,height:844})
 await page.waitForTimeout(100)
 const bounds=JSON.parse(await canvas.getAttribute('data-cassette-bounds'))
 assert.ok(bounds.minX>-.91&&bounds.maxX<.91&&bounds.minY>-.91&&bounds.maxY<.91)
 for(const card of await page.locator('.ar-card').all())await card.click({trial:true})
 await page.screenshot({path:join(output,'closeup-mobile.png')})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.keyboard.press('Escape')
 await page.waitForFunction(()=>document.querySelector('.ar-cabinet-wrap').dataset.caseState==='closed')
 assert.equal(await page.locator('.ar-top').isVisible(),true)
 assert.ok(Math.abs(Number(await canvas.getAttribute('data-azimuth'))+Math.PI/2)<.01)
 assert.deepEqual(errors,[])
 console.log(`PASS: front-facing arrival, supported set-down before opening, staged lid pause and second zoom, unchanged background, front-facing cassette close-up, mobile click targets and reverse close. Screenshots: ${output}`)
}finally{await browser.close()}
