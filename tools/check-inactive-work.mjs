import assert from 'node:assert/strict'
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']})
try{
  const page=await browser.newPage({ignoreHTTPSErrors:true,viewport:{width:800,height:700},reducedMotion:'reduce'}),errors=[]
  page.on('pageerror',e=>errors.push(String(e)))
  await page.route('**/src/planet-neon-background-layer.ts*',async route=>{
    const response=await route.fetch(),body=await response.text()
    assert.ok(body.includes('background.render(context,'))
    await route.fulfill({response,body:body.replace('background.render(context,','window.skyPaints=(window.skyPaints||0)+1; background.render(context,')})
  })
  await page.route('**/src/planet-world.ts*',async route=>{
    const response=await route.fetch(),body=await response.text()
    await route.fulfill({response,body:body.replace('environment.update(now)','(window.envUpdates=(window.envUpdates||0)+1,environment.update(now))').replace('renderer.render(scene, camera)','(window.draws=(window.draws||0)+1,renderer.render(scene, camera))')})
  })
  await page.goto(process.env.REVIEW_URL||'https://localhost:5173')
  await page.clock.install();await page.clock.pauseAt(new Date())
  await page.evaluate(async()=>{
    const {createParangePlanetExperience}=await import('/src/parange-planet.ts')
    window.app=createParangePlanetExperience();app.open()
  })
  await page.locator('[data-mode=neon]').evaluate(el=>el.click())
  await page.evaluate(async()=>{const {loadSkyArtwork}=await import('/src/neon-sky-art.ts');await loadSkyArtwork()})
  await page.clock.runFor(100)
  const counts=()=>page.evaluate(()=>({sky:window.skyPaints||0,env:window.envUpdates||0,draws:window.draws||0}))
  const image=()=>page.locator('.planet-neon-canvas').evaluate(c=>c.toDataURL())
  const still=await image(),before=await counts()
  assert.ok(before.sky>0&&before.draws>0,'Test instrumentation did not run')
  await page.clock.runFor(400)
  assert.equal((await counts()).sky,before.sky,'Reduced-motion sky repaints identical pixels')
  assert.equal(await image(),still)
  await page.evaluate(()=>dispatchEvent(new Event('resize')));await page.clock.runFor(100)
  assert.equal((await counts()).sky,before.sky,'Unchanged resize discarded the cache')
  await page.setViewportSize({width:810,height:700});await page.clock.runFor(100)
  assert.equal((await counts()).sky,before.sky+1,'Resize must refresh the still')
  await page.emulateMedia({reducedMotion:'no-preference'});await page.clock.runFor(150)
  assert.ok((await counts()).sky>before.sky+1,'Motion preference change did not resume animation')
  await page.locator('.planet-join-primary').evaluate(el=>el.click())
  const covered=await counts();await page.clock.runFor(400)
  assert.deepEqual(await counts(),covered,'Opaque studio still runs hidden effects/rendering')
  await page.locator('.planet-studio-close').evaluate(el=>el.click());await page.clock.runFor(100)
  assert.ok((await counts()).env>covered.env)
  await page.evaluate(async()=>{
    const {createResidentRig}=await import('/src/resident-model.ts'),{createPlanetArrival}=await import('/src/planet-arrival.ts')
    document.querySelector('.planet-arrival').remove();document.querySelector('.planet-reveal-backdrop').remove()
    const ui=createPlanetArrival(document.querySelector('.planet-screen'))
    const model={...createResidentRig(0),designIndex:0,name:'Momo',portrait:'',trait:'Explorer',mapped:false}
    ui.show(model);app.world.presentResident(model,ui.fly,ui.hide,ui.getFrame,ui.update)
  })
  const reveal=await counts();await page.clock.runFor(350)
  const showing=await counts()
  assert.equal(showing.sky,reveal.sky);assert.equal(showing.env,reveal.env)
  assert.ok(showing.draws>reveal.draws,'Visible capsule was paused')
  await page.clock.fastForward(5600)
  assert.ok((await counts()).env>showing.env,'Planet effects did not resume during flight')
  await page.evaluate(()=>{
    window.reviewHidden=true;Object.defineProperty(document,'hidden',{configurable:true,get:()=>window.reviewHidden})
    document.dispatchEvent(new Event('visibilitychange'))
  })
  const hidden=await counts();await page.clock.runFor(400)
  assert.deepEqual(await counts(),hidden,'Hidden tab still renders')
  await page.evaluate(()=>{window.reviewHidden=false;document.dispatchEvent(new Event('visibilitychange'))})
  await page.clock.runFor(100);assert.ok((await counts()).draws>hidden.draws)
  await page.evaluate(()=>app.close())
  const closed=await counts();await page.clock.runFor(400)
  assert.deepEqual(await counts(),closed)
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({reducedSkyCached:true,resizeInvalidation:true,motionResumes:true,studioWorkPaused:true,revealBackgroundPaused:true,hiddenTabPaused:true,closedPaused:true,errors},null,2))
}finally{await browser.close()}
