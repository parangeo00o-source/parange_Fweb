export function createDialogueDeck(random:()=>number=Math.random) {
  let remaining:number[]=[],last=-1
  return ()=>{
    if(!remaining.length){
      remaining=residentLines.map((_,i)=>i)
      for(let i=remaining.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[remaining[i],remaining[j]]=[remaining[j],remaining[i]]}
      if(remaining.at(-1)===last)[remaining[0],remaining[remaining.length-1]]=[remaining[remaining.length-1],remaining[0]]
    }
    last=remaining.pop()!
    return residentLines[last]
  }
}
